// Renders app/design/tokens.js into every surface that needs it.
//
//   app/web/src/tokens.css                  — imported by main.jsx
//   tutor_data/dashboard.html               — inlined between markers
//   tutor_data/dashboard-site/index.html    — inlined between markers
//
// The two standalone HTML files cannot import CSS, so their token block is
// written INTO them between GENERATED markers. That is what stops the four
// surfaces drifting apart again. Run: npm run tokens  (wired as prebuild)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  NEUTRAL, HUE, MOOD, MODE_HUE, FONT, SIZE, LEADING, WEIGHT,
  SPACE, RADIUS, SHADOW, MOTION, LAYOUT,
} from '../design/tokens.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.join(HERE, '..');
const ROOT = path.join(APP, '..');

const BEGIN = '/* ═══ MONDAY DESIGN TOKENS — GENERATED BY app/scripts/build-tokens.mjs — DO NOT EDIT ═══ */';
const END = '/* ═══ END MONDAY DESIGN TOKENS ═══ */';

/** The variable block for one theme. Shared by all four surfaces verbatim. */
function themeVars(theme) {
  const n = NEUTRAL[theme];
  const sh = SHADOW[theme];
  const L = [];
  L.push(`  --bg: ${n.bg};`);
  L.push(`  --surface: ${n.surface};`);
  L.push(`  --sunken: ${n.sunken};`);
  L.push(`  --raised: ${n.raised};`);
  L.push(`  --line: ${n.lineStrong === n.line ? n.line : n.line};`);
  L.push(`  --line-strong: ${n.lineStrong};`);
  L.push(`  --ink: ${n.ink};`);
  L.push(`  --ink-2: ${n.ink2};`);
  L.push(`  --ink-3: ${n.ink3};`);
  L.push('');
  for (const [name, val] of Object.entries(HUE)) {
    L.push(`  --c-${name}: ${val[theme].fill};`);
    L.push(`  --c-${name}-ink: ${val[theme].ink};`);
    if (val[theme].soft) L.push(`  --c-${name}-soft: ${val[theme].soft};`);
  }
  L.push('');
  for (const [mood, val] of Object.entries(MOOD)) {
    L.push(`  --mood-${mood}: ${val[theme]};`);
    L.push(`  --mood-${mood}-on: ${theme === 'light' ? val.onLight : val.onDark};`);
  }
  L.push('');
  for (const [k, v] of Object.entries(sh)) L.push(`  --shadow-${k}: ${v};`);
  return L.join('\n');
}

/** Everything that does not change between themes. */
function staticVars() {
  const L = [];
  L.push(`  --font-sans: ${FONT.sans};`);
  L.push(`  --font-mono: ${FONT.mono};`);
  L.push('');
  for (const [k, v] of Object.entries(SIZE)) L.push(`  --t-${k}: ${v};`);
  L.push('');
  for (const [k, v] of Object.entries(LEADING)) L.push(`  --lh-${k}: ${v};`);
  for (const [k, v] of Object.entries(WEIGHT)) L.push(`  --fw-${k}: ${v};`);
  L.push('');
  for (const [k, v] of Object.entries(SPACE)) L.push(`  --sp-${k}: ${v};`);
  L.push('');
  for (const [k, v] of Object.entries(RADIUS)) L.push(`  --r-${k}: ${v};`);
  L.push('');
  for (const [k, v] of Object.entries(MOTION)) L.push(`  --motion-${k}: ${v};`);
  L.push('');
  for (const [k, v] of Object.entries(LAYOUT)) L.push(`  --layout-${k}: ${v};`);
  L.push('');
  for (const [mode, hue] of Object.entries(MODE_HUE)) L.push(`  --mode-${mode.toLowerCase()}: var(--c-${hue});`);
  return L.join('\n');
}

/**
 * Light is the bare :root so it is always defined; dark is applied both by an
 * explicit [data-theme='dark'] (the in-app toggle) and by prefers-color-scheme
 * guarded against an explicit light choice, so the toggle wins in both
 * directions and a system-default viewer still gets a real theme.
 */
function tokenBlock() {
  return [
    BEGIN,
    ':root, :root[data-theme="light"] {',
    themeVars('light'),
    '',
    staticVars(),
    '}',
    '',
    ':root[data-theme="dark"] {',
    themeVars('dark'),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    themeVars('dark').split('\n').map((l) => (l ? `  ${l}` : l)).join('\n'),
    '  }',
    '}',
    END,
  ].join('\n');
}

const block = tokenBlock();

// ── 1. the React app ────────────────────────────────────────────────────────
const cssPath = path.join(APP, 'web', 'src', 'tokens.css');
fs.writeFileSync(cssPath, `${block}\n`);
console.log('wrote', path.relative(ROOT, cssPath));

// ── 2 + 3. the two standalone HTML surfaces ─────────────────────────────────
// Replace between the markers if they are already there, otherwise inject a new
// <style> immediately after <head> so the tokens land before any other rule.
function inject(file) {
  if (!fs.existsSync(file)) { console.log('skip (missing)', path.relative(ROOT, file)); return; }
  let html = fs.readFileSync(file, 'utf8');
  const reBlock = new RegExp(
    `${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`
  );
  if (reBlock.test(html)) {
    html = html.replace(reBlock, block);
  } else {
    html = html.replace(/<head>/i, `<head>\n<style id="monday-tokens">\n${block}\n</style>`);
  }
  fs.writeFileSync(file, html);
  console.log('wrote', path.relative(ROOT, file));
}

inject(path.join(ROOT, 'tutor_data', 'dashboard.html'));
inject(path.join(ROOT, 'tutor_data', 'dashboard-site', 'index.html'));
inject(path.join(ROOT, 'tutor_data', 'dashboard-site', 'tyler.html'));
